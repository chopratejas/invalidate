def _c(
    id: str,
    category: str,
    memory: str,
    kind: str,
    event: str,
    event_source: str,
    expected: str,
    note: str,
    lenient: list[str] | None = None,
) -> dict:
    d = {
        "id": id,
        "category": category,
        "memory": memory,
        "kind": kind,
        "event": event,
        "event_source": event_source,
        "expected": expected,
        "note": note,
    }
    if lenient:
        if expected not in lenient:
            lenient = [expected, *lenient]
        d["lenient"] = lenient
    return d


