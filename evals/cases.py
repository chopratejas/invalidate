def validate(cases: list[dict] = CASES) -> None:
    """Raise if the dataset is malformed."""
    seen: set[str] = set()
    for c in cases:
        for key in ("id", "category", "memory", "kind", "event", "event_source", "expected", "note"):
            if key not in c:
                raise ValueError(f"{c.get('id', '?')}: missing {key}")
        if c["id"] in seen:
            raise ValueError(f"duplicate id {c['id']}")
        seen.add(c["id"])
        if c["category"] not in CATEGORIES:
            raise ValueError(f"{c['id']}: unknown category {c['category']}")
        if c["kind"] not in KINDS:
            raise ValueError(f"{c['id']}: unknown kind {c['kind']}")
        if c["expected"] not in EXPECTED_LABELS:
            raise ValueError(f"{c['id']}: unknown expected {c['expected']}")
        for alt in c.get("lenient", []):
            if alt not in EXPECTED_LABELS:
                raise ValueError(f"{c['id']}: unknown lenient label {alt}")
        if c["category"] != "long_event":
            for field in ("memory", "event"):
                if len(c[field].split()) > 70:
                    raise ValueError(f"{c['id']}: {field} is over 70 words")


def acceptable(case: dict) -> set[str]:
    return {case["expected"], *case.get("lenient", [])}


