"""Labeled evaluation cases for invalidate.

Each case is one (memory, event) pair and the disposition a careful human would
expect from `Policy().dispose(votes)` after Jev has judged the pair:

    unrelated    the event says nothing about what the memory describes
    confirmed    the memory still holds (restated, unchanged, or only temporarily disturbed)
    contradicted the memory no longer holds and the event gives no replacement value
    superseded   the memory no longer holds and the event states the new value
    uncertain    the event bears on the memory but the verdict is genuinely unclear
                 (hypothetical, partial change, ...)

`expected` is the strict label. `lenient` (optional) lists the labels that are also
acceptable; it always contains `expected`. Categories are described in README.md.

Every string except the `long_event` events is under ~60 words, and every case is
answerable by a human from the two strings alone.
"""
